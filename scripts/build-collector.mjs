import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';import path from 'node:path';
import {syncCollector} from './sync-collector.mjs';
import {makeZip} from '../public/collector/zip.js';
import {buildCollectorIcons} from './build-collector-icons.mjs';
import {buildFloating} from './build-floating.mjs';
import {sourceIdentity} from './source-identity.mjs';
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
await syncCollector();
await buildCollectorIcons();
await buildFloating();
const names=['manifest.json','service-worker.js','popup.html','capture.css','capture.js','recorder.html','recorder.js','sidepanel.html','desk.js','inbox.js','core.js','browser.js','catalog.json','lib.js','README.md',...['attachments.js','media-store.js','recipes.js','zip.js','screen-recorder.js'].map(n=>'shared/'+n)];
names.push(...[16,32,48,128].map(size=>'icons/icon-'+size+'.png'));
names.push('floating.js','floating-background.js','native-recording.js','pending-shots.js','offscreen.html','offscreen.js','cloud-connection.js','connect.html','connect.css','connect.js','shared/capture-region.js','shared/cloud-media.js');
const files=[];for(const name of names)files.push({name,data:new Uint8Array(await readFile(path.join(root,'采集器',name)))});
files.push({name:'LICENSE',data:new Uint8Array(await readFile(path.join(root,'LICENSE')))});
const identity=sourceIdentity(root,['LICENSE','scripts/build-collector.mjs','scripts/source-identity.mjs',...names.map(n=>'采集器/'+n),...['floating-ui.js','screen-recorder.js'].map(n=>'public/collector/'+n)]);
const candidate=identity&&Number.isInteger(identity.pullRequest)&&identity.pullRequest>0;
if(process.env.REFELLOW_REQUIRE_CANDIDATE==='1'&&!candidate)throw Error('正式候选要求已跟踪且干净的 Git 源码身份');
const releaseIdentity={schema:'refellow-collector-release/v1',version:'0.5.0',kind:candidate?'git-source-candidate':'local-development-source-not-store-release',...identity};
files.push({name:'release-identity.json',data:new TextEncoder().encode(JSON.stringify(releaseIdentity,null,2)+'\n')});
const blob=await makeZip(files),bytes=Buffer.from(await blob.arrayBuffer());
const out=path.join(root,'public/assets/collector.zip');await writeFile(out,bytes);
console.log(JSON.stringify({...releaseIdentity,path:out,files:files.map(f=>f.name),bytes:bytes.length,sha256:createHash('sha256').update(bytes).digest('hex')},null,2));
